/**
 * Generates a centered, beveled 3D extruded geometry for an uppercase letter.
 */
export function createExtrudedLetterGeometry(char: string): THREE.ExtrudeGeometry {
  const key = char.toUpperCase();
  const factory = LETTER_SHAPES[key] ?? LETTER_SHAPES.U;
  const shape = factory();

  const geometry = new THREE.ExtrudeGeometry(shape, {
    depth: 0.28,
    bevelEnabled: true,
    bevelThickness: 0.055,
    bevelSize: 0.038,
    bevelSegments: 3,
    curveSegments: 6,
  });

  geometry.center();
  geometry.computeVertexNormals();
  return geometry;
}
